def _classify(id: str, units: str) -> tuple[str, bool]:
    """Return (role, perturb); every reviewed id is matched by exactly one rule."""
    if id in _STRUCTURAL or id.startswith("v2.world.UNITS_PER_TAIL[") or id.startswith(_P + "engine._SHARES["):
        role = "structural"
    elif id in _ANCHOR or id.startswith("v2.drivers.STATION_ENV["):
        role = "anchor"
    elif id in _THRESHOLD or id.startswith(("constants.LLP_CYCLE_LIMITS[", "v2.world.POLICY[")):
        role = "threshold"
    elif id == "v2.drivers.TAXI_SPEED_KMH" or id.startswith(("v2.coupling.", _P + "engine._MASKS[")):
        role = "shape"
    elif id.startswith("v2.faults.LIBRARY[") and id.endswith(".base_hazard"):
        role = "rate"
    elif id.startswith("v2.faults.") or (id.startswith("v2.world.") and not id.startswith(("v2.world.FALSE_CALL[", "v2.world.SENSOR_FAULT"))):
        role = "shape"
    elif re.search(r"sigma|noise|_sd", id.rsplit(".", 1)[-1].lower()):
        role = "shape"
    elif _RATE_UNITS.search(units) or _RATE_KEYS.search(id.rsplit(".", 1)[-1].lower()):
        role = "rate"
    else:
        role = "shape"
    return role, role not in _FIXED_ROLES


def _provenance(id: str) -> tuple[str, str | None, str]:
    if id in _CALIBRATED:
        key = id.split("[")[1].rstrip("]")
        return "calibrated", f"{_NASA} decisions.{key}", "Changed by the small-sample cell fit"
    if id in _HYD_CHECKED:
        return "sensor_shape_checked", _UCI, "Rig comparison retained the prior (noise floor or sign/uncertainty conflict)"
    if id == "v2.models.electrical.PARAMS[resistance_rate]":
        return "sensor_shape_checked", _NASA, "R/R0 growth compared; extra growth remains a prior and may double-count fade"
    if id in _ENGINE_CHECKED:
        return "sensor_shape_checked", "docs/SIM-V2-ENGINE.md; NASA C-MAPSS FD001-FD004", "Cycles-to-failure comparison; no parameter override"
    return "assumed", None, "Assumed prior; no fleet or transferable public-data fit in repo"


