def _numeric(value: Any) -> bool:
    return isinstance(value, Real) and not isinstance(value, bool)


def _leaves(value: Any, prefix: str) -> Iterator[str]:
    """Walk numeric leaves; strings, flags, arrays and classes are not tunables."""
    if _numeric(value):
        yield prefix
    elif is_dataclass(value) and not isinstance(value, type):
        for field in fields(value):
            yield from _leaves(getattr(value, field.name), f"{prefix}.{field.name}")
    elif isinstance(value, dict):
        for key, child in value.items():
            yield from _leaves(child, f"{prefix}[{key}]")
    elif isinstance(value, (tuple, list)):
        for index, child in enumerate(value):
            yield from _leaves(child, f"{prefix}[{index}]")


def _imported_names(module: Any) -> set[str]:
    """Avoid duplicates of constants imported from other scoped modules."""
    tree = ast.parse(Path(module.__file__).read_text(encoding="utf-8"))
    return {
        alias.asname or alias.name
        for node in tree.body
        if isinstance(node, ast.ImportFrom) and node.module in {f"app.sim.{name}" for name in _MODULES}
        for alias in node.names
    }


def _live_ids() -> set[str]:
    found: set[str] = set()
    for name in _MODULES:
        module = import_module(f"app.sim.{name}")
        imported = _imported_names(module)
        for key, value in vars(module).items():
            if key.isupper() and key not in _EXCLUDED_NAMES and key not in imported:
                found.update(_leaves(value, f"{name}.{key}"))
        if name == "v2.coupling":
            for edge in module.default_edges():
                found.update(_leaves(edge, f"{name}.{edge.name}"))
    return found


def _module_for(id: str) -> str:
    return next(name for name in sorted(_MODULES, key=len, reverse=True) if id.startswith(f"{name}."))


def _reader(id: str) -> Callable[[], float]:
    module_name = _module_for(id)
    suffix = id[len(module_name) + 1:]
    root = re.split(r"[.\[]", suffix, maxsplit=1)[0]
    steps = re.findall(r"\.([^.[\]]+)|\[([^\]]+)\]", suffix[len(root):])

    def read() -> float:
        module = import_module(f"app.sim.{module_name}")
        if module_name == "v2.coupling" and not root.isupper():
            value = next(edge for edge in module.default_edges() if edge.name == root)
        else:
            value = getattr(module, root)
        for attribute, key in steps:
            if attribute:
                value = getattr(value, attribute)
            else:
                value = value[int(key) if isinstance(value, (tuple, list)) else key]
        return float(value)

    return read


def _keys(module: str, *keys: str) -> frozenset[str]:
    return frozenset(f"{module}{'' if key.startswith('[') else '.'}{key}" for key in keys)


