def registry() -> list[Param]:
    """Return reviewed parameters sorted by stable id, with live readers."""
    result = []
    for id, units, low, high, bound_reason, notes in _SPECS:
        source, citation, reason = _provenance(id)
        role, perturb = _classify(id, units)
        result.append(Param(id, units, low, high, f"{reason}; {bound_reason}.", source, citation, notes, _reader(id), role, perturb))
    return sorted(result, key=lambda param: param.id)


def get(id: str) -> Param:
    """Return a reviewed parameter; unknown ids raise KeyError."""
    for param in registry():
        if param.id == id:
            return param
    raise KeyError(id)


def bounds(id: str) -> tuple[float, float]:
    """Return the reviewed sensitivity bounds."""
    param = get(id)
    return param.low, param.high


def coverage_gaps() -> tuple[list[str], list[str]]:
    """Compare independently discovered live leaves with reviewed metadata."""
    live = _live_ids()
    reviewed = {param.id for param in registry()}
    unclassified = {f"{param.id} (role)" for param in registry() if param.role not in ROLES}
    return sorted((live - reviewed) | unclassified), sorted(reviewed - live)


def _cell(value: str) -> str:
    return value.replace("|", "\\|").replace("\r\n", " ").replace("\r", " ").replace("\n", " ")


def render_markdown() -> str:
    """Render deterministic provenance tables using current values."""
    params = registry()
    counts = Counter(param.source_type for param in params)
    lines = ["# Simulation parameter provenance", "", "Generated by `python -m app.sim.v2.params_registry --markdown`.", ""]
    lines.extend(f"- {source}: {counts[source]}" for source in _SOURCE_TYPES)
    roles = Counter(param.role for param in params)
    lines.extend([f"- total: {len(params)}", "", "Roles (perturb is false for anchor and structural):", ""])
    lines.extend(f"- {role}: {roles[role]}" for role in ROLES)
    lines.extend([
        f"- perturbable: {sum(param.perturb for param in params)}", "", "## Registry notes", "",
        "Role: rate, shape and threshold entries are perturbed by sensitivity analysis. anchor entries define the "
        "healthy/limit/nominal/reference scale of a signal, a unit or time conversion or a physical coordinate; "
        "structural entries are counts or mixing structure. Both are fixed by default (perturb = false) because "
        "scaling them re-labels outputs rather than testing a belief.",
        "C-MAPSS curves, noise and life distributions are fitted in engine_fit.json; they are artifacts, not PARAMS overrides, and its data arrays are excluded.",
        "Bounds are sensitivity ranges, not confidence intervals. Generic bounds span one third to three times the reviewed value; zero-valued controls use stated absolute ranges.",
        "Imported names and PRIOR_PARAMS snapshots are excluded. Locally assigned aliases and mutable PARAMS slots remain independently readable, even when initialized from shared constants.",
        "Private UPPER_CASE numeric containers are included. Coupling readers call default_edges() afresh; "
        "boolean edge flags and numeric literals inside functions are outside the requested leaf scope.",
        "Documentation notes distinguish specific named mentions from general model descriptions; a mention alone is not evidence of a public-data comparison.",
        "", "## Constants without a specific mention in existing docs", "",
        "The following assumed ids have no specific named mention in docs (excluding this generated file), grouped by defining module.", "",
    ])
    for module in sorted({_module_for(param.id) for param in params}):
        missing = [param.id for param in params if _module_for(param.id) == module and "No specific named mention in existing docs" in param.notes]
        if missing:
            lines.append(f"- {module}: " + ", ".join(f"`{id}`" for id in missing))
    for source in _SOURCE_TYPES:
        lines.extend(["", f"## {source}"])
        modules = sorted({_module_for(param.id) for param in params if param.source_type == source})
        for module in modules:
            lines.extend(["", f"### {module}", "", "| id | value | units | low | high | source_type | role | perturb | citation | rationale | notes |",
                          "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |"])
            for param in params:
                if param.source_type != source or _module_for(param.id) != module:
                    continue
                row = (param.id, format(param.value, ".6g"), param.units, format(param.low, ".6g"), format(param.high, ".6g"),
                       param.source_type, param.role, str(param.perturb).lower(), param.citation or "", param.rationale, param.notes)
                lines.append("| " + " | ".join(_cell(cell) for cell in row) + " |")
    return "\n".join(lines) + "\n"


def _repo_root() -> Path:
    root = Path(__file__).resolve().parents[3]
    if not all((root / marker).exists() for marker in (".git", "app/sim/v2/params_registry.py", "docs", "tests", "ruff.toml")):
        raise RuntimeError(f"Not the repository root: {root}")
    return root


def _main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--markdown", action="store_true", help="Generate docs/PARAMETERS.md")
    args = parser.parse_args()
    if args.markdown:
        (_repo_root() / "docs/PARAMETERS.md").write_text(render_markdown(), encoding="utf-8")
    else:
        counts = Counter(param.source_type for param in registry())
        for source in _SOURCE_TYPES:
            print(f"{source}: {counts[source]}")
        missing, stale = coverage_gaps()
        print("roles: " + ", ".join(f"{role}={sum(p.role == role for p in registry())}" for role in ROLES))
        print(f"Missing from registry: {missing}")
        print(f"Not found in live code: {stale}")


if __name__ == "__main__":
    _main()
